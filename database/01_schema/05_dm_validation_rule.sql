-- =====================================================================
-- DataMind AI | DM_VALIDATION_RULE
-- Configurable data-quality rules. Rule behaviour comes from a fixed set
-- of RULE_TYPEs plus JSON settings - never from executable expressions.
-- =====================================================================
CREATE TABLE DM_VALIDATION_RULE
(
    RULE_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RULE_CODE       VARCHAR2(100)  NOT NULL,
    RULE_NAME       VARCHAR2(250)  NOT NULL,
    TABLE_NAME      VARCHAR2(128)  NOT NULL,
    COLUMN_NAME     VARCHAR2(128),
    RULE_TYPE       VARCHAR2(50)   NOT NULL,
    RULE_CONFIG     CLOB,
    SEVERITY        VARCHAR2(20)   DEFAULT 'ERROR' NOT NULL,
    RULE_PRIORITY   NUMBER         DEFAULT 1 NOT NULL,
    IS_ACTIVE       CHAR(1)        DEFAULT 'Y' NOT NULL,
    RULE_VERSION    NUMBER         DEFAULT 1 NOT NULL,
    EFFECTIVE_FROM  DATE           DEFAULT TRUNC(SYSDATE) NOT NULL,
    EFFECTIVE_TO    DATE,
    CREATED_DATE    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_DATE    TIMESTAMP,
    CONSTRAINT DM_VALIDATION_RULE_PK PRIMARY KEY (RULE_ID),
    CONSTRAINT DM_RULE_CODE_UK UNIQUE (RULE_CODE),
    CONSTRAINT DM_RULE_TYPE_CK CHECK (RULE_TYPE IN
        ('REQUIRED','EMAIL','PHONE','REGEX','LENGTH','RANGE','UNIQUE','LOOKUP')),
    CONSTRAINT DM_RULE_SEVERITY_CK CHECK (SEVERITY IN ('ERROR','WARNING')),
    CONSTRAINT DM_RULE_ACTIVE_CK CHECK (IS_ACTIVE IN ('Y','N')),
    CONSTRAINT DM_RULE_VERSION_CK CHECK (RULE_VERSION >= 1),
    CONSTRAINT DM_RULE_CONFIG_JSON_CK CHECK (RULE_CONFIG IS JSON),
    CONSTRAINT DM_RULE_EFFECTIVE_CK CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM)
);

COMMENT ON TABLE  DM_VALIDATION_RULE IS 'Rule registry for the validation engine (PKG_DM_VALIDATION).';
COMMENT ON COLUMN DM_VALIDATION_RULE.RULE_CONFIG IS 'JSON settings for the rule type, e.g. {"min":2,"max":250} for LENGTH.';
