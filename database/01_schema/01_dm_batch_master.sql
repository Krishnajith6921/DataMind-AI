-- =====================================================================
-- DataMind AI | DM_BATCH_MASTER
-- One row per ingestion batch (one uploaded file / API load).
-- Parent of staging rows, attempts, validation results and incidents.
-- =====================================================================
CREATE TABLE DM_BATCH_MASTER
(
    BATCH_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BATCH_NAME         VARCHAR2(200)  NOT NULL,
    SOURCE_NAME        VARCHAR2(100)  NOT NULL,
    SOURCE_FILE_NAME   VARCHAR2(500),
    BATCH_STATUS       VARCHAR2(30)   DEFAULT 'CREATED' NOT NULL,
    TOTAL_RECORDS      NUMBER         DEFAULT 0 NOT NULL,
    PROCESSED_RECORDS  NUMBER         DEFAULT 0 NOT NULL,
    SUCCESS_RECORDS    NUMBER         DEFAULT 0 NOT NULL,
    FAILED_RECORDS     NUMBER         DEFAULT 0 NOT NULL,
    WARNING_RECORDS    NUMBER         DEFAULT 0 NOT NULL,
    CORRELATION_ID     VARCHAR2(64),
    CREATED_BY         VARCHAR2(100)  DEFAULT SYS_CONTEXT('USERENV','SESSION_USER'),
    CREATED_DATE       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    START_DATE         TIMESTAMP,
    END_DATE           TIMESTAMP,
    UPDATED_DATE       TIMESTAMP,
    ERROR_MESSAGE      VARCHAR2(4000),
    CONSTRAINT DM_BATCH_MASTER_PK PRIMARY KEY (BATCH_ID),
    CONSTRAINT DM_BATCH_STATUS_CK CHECK (BATCH_STATUS IN
        ('CREATED','UPLOADED','VALIDATING','READY','PROCESSING',
         'COMPLETED','PARTIAL','FAILED','CANCELLED')),
    CONSTRAINT DM_BATCH_COUNTS_CK CHECK (TOTAL_RECORDS >= 0 AND PROCESSED_RECORDS >= 0
        AND SUCCESS_RECORDS >= 0 AND FAILED_RECORDS >= 0 AND WARNING_RECORDS >= 0),
    CONSTRAINT DM_BATCH_DATES_CK CHECK (START_DATE IS NULL OR END_DATE IS NULL OR END_DATE >= START_DATE)
);

COMMENT ON TABLE  DM_BATCH_MASTER IS 'Batch header: one row per ingestion batch, its lifecycle status and record counters.';
COMMENT ON COLUMN DM_BATCH_MASTER.BATCH_STATUS   IS 'Lifecycle state; valid transitions are enforced by PKG_DM_BATCH.';
COMMENT ON COLUMN DM_BATCH_MASTER.CORRELATION_ID IS 'Links UI request, API call, batch work and AI analysis in logs.';
