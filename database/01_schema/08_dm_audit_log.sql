-- =====================================================================
-- DataMind AI | DM_AUDIT_LOG
-- Who did what, to which object, when, and with what result.
-- Standalone by design (no FKs) so audit rows outlive the objects.
-- =====================================================================
CREATE TABLE DM_AUDIT_LOG
(
    AUDIT_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_NAME       VARCHAR2(100)  DEFAULT SYS_CONTEXT('USERENV','SESSION_USER') NOT NULL,
    ACTION_NAME     VARCHAR2(100)  NOT NULL,
    OBJECT_NAME     VARCHAR2(200),
    OBJECT_ID       VARCHAR2(100),
    OLD_VALUE       CLOB,
    NEW_VALUE       CLOB,
    ACTION_STATUS   VARCHAR2(30)   DEFAULT 'SUCCESS' NOT NULL,
    CORRELATION_ID  VARCHAR2(64),
    CREATED_DATE    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT DM_AUDIT_LOG_PK PRIMARY KEY (AUDIT_ID),
    CONSTRAINT DM_AUDIT_STATUS_CK CHECK (ACTION_STATUS IN ('SUCCESS','FAILURE'))
);

COMMENT ON TABLE DM_AUDIT_LOG IS 'Audit trail of administrative actions, batch transitions, SQL execution and AI requests.';
