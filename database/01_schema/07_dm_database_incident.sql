-- =====================================================================
-- DataMind AI | DM_DATABASE_INCIDENT
-- Captured Oracle errors (code, stack, backtrace, where it happened).
-- BATCH_ID has no FK on purpose: error logging must never fail because
-- of the very data problem it is trying to record.
-- =====================================================================
CREATE TABLE DM_DATABASE_INCIDENT
(
    INCIDENT_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BATCH_ID           NUMBER,
    ERROR_CODE         NUMBER,
    ERROR_MESSAGE      VARCHAR2(4000),
    ERROR_STACK        CLOB,
    ERROR_BACKTRACE    CLOB,
    MODULE_NAME        VARCHAR2(200),
    PROCEDURE_NAME     VARCHAR2(200),
    EXECUTION_CONTEXT  CLOB,
    CORRELATION_ID     VARCHAR2(64),
    INCIDENT_STATUS    VARCHAR2(30)    DEFAULT 'OPEN' NOT NULL,
    CREATED_DATE       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    RESOLVED_DATE      TIMESTAMP,
    CONSTRAINT DM_DATABASE_INCIDENT_PK PRIMARY KEY (INCIDENT_ID),
    CONSTRAINT DM_INCIDENT_STATUS_CK CHECK (INCIDENT_STATUS IN ('OPEN','ANALYZING','RESOLVED','CLOSED')),
    CONSTRAINT DM_INCIDENT_CONTEXT_JSON_CK CHECK (EXECUTION_CONTEXT IS JSON)
);

COMMENT ON TABLE DM_DATABASE_INCIDENT IS 'Database error incidents captured by PKG_DM_INCIDENT, later analysed by AI.';
