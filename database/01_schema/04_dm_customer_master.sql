-- =====================================================================
-- DataMind AI | DM_CUSTOMER_MASTER
-- Clean, validated customer records (the system of record).
-- SOURCE_STAGING_ID is unique: a staging row can be loaded only once,
-- so retrying a batch never creates duplicate master records.
-- No FK to staging on purpose: staging data may be archived/purged later.
-- =====================================================================
CREATE TABLE DM_CUSTOMER_MASTER
(
    CUSTOMER_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CUSTOMER_CODE      VARCHAR2(100),
    CUSTOMER_NAME      VARCHAR2(250)  NOT NULL,
    EMAIL              VARCHAR2(250),
    PHONE              VARCHAR2(30),
    CUSTOMER_TYPE      VARCHAR2(50),
    DATE_OF_BIRTH      DATE,
    SOURCE_BATCH_ID    NUMBER         NOT NULL,
    SOURCE_STAGING_ID  NUMBER         NOT NULL,
    CREATED_DATE       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_DATE       TIMESTAMP,
    CONSTRAINT DM_CUSTOMER_MASTER_PK PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT DM_CUSTOMER_BATCH_FK FOREIGN KEY (SOURCE_BATCH_ID)
        REFERENCES DM_BATCH_MASTER (BATCH_ID),
    CONSTRAINT DM_CUSTOMER_CODE_UK UNIQUE (CUSTOMER_CODE),
    CONSTRAINT DM_CUSTOMER_STAGING_UK UNIQUE (SOURCE_STAGING_ID)
);

COMMENT ON TABLE  DM_CUSTOMER_MASTER IS 'Validated customer records loaded from staging.';
COMMENT ON COLUMN DM_CUSTOMER_MASTER.SOURCE_STAGING_ID IS 'Staging row this record came from; unique to make retries idempotent.';
