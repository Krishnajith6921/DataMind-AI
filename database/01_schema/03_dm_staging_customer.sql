-- =====================================================================
-- DataMind AI | DM_STAGING_CUSTOMER
-- Raw incoming customer rows, exactly as received, before validation.
-- (BATCH_ID, SOURCE_ROW_NO) is unique so re-loading a file cannot
-- create the same staging row twice (idempotency).
-- =====================================================================
CREATE TABLE DM_STAGING_CUSTOMER
(
    STAGING_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BATCH_ID         NUMBER         NOT NULL,
    SOURCE_ROW_NO    NUMBER         NOT NULL,
    CUSTOMER_CODE    VARCHAR2(100),
    CUSTOMER_NAME    VARCHAR2(250),
    EMAIL            VARCHAR2(250),
    PHONE            VARCHAR2(30),
    CUSTOMER_TYPE    VARCHAR2(50),
    DATE_OF_BIRTH    DATE,
    RECORD_STATUS    VARCHAR2(30)   DEFAULT 'NEW' NOT NULL,
    SOURCE_PAYLOAD   CLOB,
    CREATED_DATE     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    PROCESSED_DATE   TIMESTAMP,
    CONSTRAINT DM_STAGING_CUSTOMER_PK PRIMARY KEY (STAGING_ID),
    CONSTRAINT DM_STAGING_BATCH_FK FOREIGN KEY (BATCH_ID)
        REFERENCES DM_BATCH_MASTER (BATCH_ID),
    CONSTRAINT DM_STAGING_SOURCE_ROW_UK UNIQUE (BATCH_ID, SOURCE_ROW_NO),
    CONSTRAINT DM_STAGING_STATUS_CK CHECK (RECORD_STATUS IN
        ('NEW','VALID','WARNING','INVALID','DUPLICATE','PROCESSED','FAILED')),
    CONSTRAINT DM_STAGING_PAYLOAD_JSON_CK CHECK (SOURCE_PAYLOAD IS JSON)
);

COMMENT ON TABLE  DM_STAGING_CUSTOMER IS 'Landing area for incoming customer rows before validation and loading.';
COMMENT ON COLUMN DM_STAGING_CUSTOMER.SOURCE_ROW_NO  IS 'Row number in the source file; unique within a batch for safe re-loads.';
COMMENT ON COLUMN DM_STAGING_CUSTOMER.SOURCE_PAYLOAD IS 'Original record as JSON, kept for audit and troubleshooting.';
