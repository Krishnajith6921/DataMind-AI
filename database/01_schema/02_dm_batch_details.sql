-- =====================================================================
-- DataMind AI | DM_BATCH_DETAILS
-- One row per execution attempt of a batch step (validate / process).
-- Gives the attempt history needed for retries and auditing.
-- =====================================================================
CREATE TABLE DM_BATCH_DETAILS
(
    DETAIL_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BATCH_ID         NUMBER        NOT NULL,
    STEP_NAME        VARCHAR2(30)  NOT NULL,
    ATTEMPT_NO       NUMBER        DEFAULT 1 NOT NULL,
    STEP_STATUS      VARCHAR2(30)  DEFAULT 'RUNNING' NOT NULL,
    START_DATE       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    END_DATE         TIMESTAMP,
    PROCESSED_COUNT  NUMBER        DEFAULT 0 NOT NULL,
    SUCCESS_COUNT    NUMBER        DEFAULT 0 NOT NULL,
    FAILED_COUNT     NUMBER        DEFAULT 0 NOT NULL,
    ERROR_MESSAGE    VARCHAR2(4000),
    CONSTRAINT DM_BATCH_DETAILS_PK PRIMARY KEY (DETAIL_ID),
    CONSTRAINT DM_BATCH_DETAILS_BATCH_FK FOREIGN KEY (BATCH_ID)
        REFERENCES DM_BATCH_MASTER (BATCH_ID),
    CONSTRAINT DM_BATCH_DETAILS_UK UNIQUE (BATCH_ID, STEP_NAME, ATTEMPT_NO),
    CONSTRAINT DM_BATCH_DETAILS_STEP_CK CHECK (STEP_NAME IN ('UPLOAD','VALIDATE','DEDUPLICATE','PROCESS')),
    CONSTRAINT DM_BATCH_DETAILS_STATUS_CK CHECK (STEP_STATUS IN ('RUNNING','COMPLETED','PARTIAL','FAILED')),
    CONSTRAINT DM_BATCH_DETAILS_ATTEMPT_CK CHECK (ATTEMPT_NO >= 1)
);

COMMENT ON TABLE DM_BATCH_DETAILS IS 'Attempt history: one row per run of a batch step, including retries.';
