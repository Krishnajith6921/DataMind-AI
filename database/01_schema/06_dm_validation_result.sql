-- =====================================================================
-- DataMind AI | DM_VALIDATION_RESULT
-- Row-level findings: one row per (staging record, rule) outcome.
-- A staging row can have many findings. RULE_VERSION records which
-- version of the rule produced the result.
-- =====================================================================
CREATE TABLE DM_VALIDATION_RESULT
(
    RESULT_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BATCH_ID           NUMBER          NOT NULL,
    STAGING_ID         NUMBER          NOT NULL,
    RULE_ID            NUMBER          NOT NULL,
    RULE_VERSION       NUMBER          NOT NULL,
    VALIDATION_STATUS  VARCHAR2(20)    NOT NULL,
    SEVERITY           VARCHAR2(20)    NOT NULL,
    ERROR_MESSAGE      VARCHAR2(2000),
    EXECUTION_DATE     TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT DM_VALIDATION_RESULT_PK PRIMARY KEY (RESULT_ID),
    CONSTRAINT DM_VALRES_BATCH_FK FOREIGN KEY (BATCH_ID)
        REFERENCES DM_BATCH_MASTER (BATCH_ID),
    CONSTRAINT DM_VALRES_STAGING_FK FOREIGN KEY (STAGING_ID)
        REFERENCES DM_STAGING_CUSTOMER (STAGING_ID),
    CONSTRAINT DM_VALRES_RULE_FK FOREIGN KEY (RULE_ID)
        REFERENCES DM_VALIDATION_RULE (RULE_ID),
    CONSTRAINT DM_VALRES_STATUS_CK CHECK (VALIDATION_STATUS IN ('PASS','FAIL')),
    CONSTRAINT DM_VALRES_SEVERITY_CK CHECK (SEVERITY IN ('ERROR','WARNING'))
);

COMMENT ON TABLE DM_VALIDATION_RESULT IS 'Validation findings per staging row and rule.';
